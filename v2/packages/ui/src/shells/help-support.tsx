/*
 * Help & support (GL-03, XS-07; Appendix E §3.5 "HelpSupport template"): the one template every
 * workspace shows (board 07: "One template, one location … in all seven workspaces"). Structure:
 * My reports (AR-2) + Report a problem (AR-8) + the sent confirmation (AR-10) + Report detail
 * (AR-3). The words below are the ones board 07 fixes for the template; everything about a report
 * — its id, title, dates, status words, note and history — comes from the caller. No fetching,
 * no validation rules, no sending: the caller (WP-0.8 / WP-0.13) owns all of that, and places
 * each part in the WorkspaceShell with the width board 07 draws (`read` for the list and the
 * detail, `form` for the form, `none` for the confirmation).
 *
 * Board 07's inline glue that has no v46 class is reproduced by PF-14 in the product layer
 * (WP-0.13, owner-authorised): the product classes `xr-x-help-form` (the form card and its
 * actions), `xr-x-help-back` (the back link's 8 px gap), `xr-x-help-empty` (the empty state's top
 * rule) and `xr-x-help-foot` (the detail's closing line in ink-2). Nothing else is added.
 */

const HELP = 'Help & support';
const REPORT_A_PROBLEM = 'Report a problem';
/** Board 07 "State 2 · My reports …" lead. Board 05 draws "… follow what happens to your report." */
const HOME_LEAD = 'Something isn’t working? Report it here and follow what happens.';

/** A report's status in words with its tone (board 07 "Rules": "Open · Resolved · Reopened"). */
export interface HelpReportStatus {
  readonly tone: StatusTone;
  /** The status words, from the caller's vocabulary ("Open", "Resolved", "Reopened"). */
  readonly label: string;
  /**
   * Another board icon for the tone: board 07 draws "Reopened" as an info chip with the Retry
   * arrow (`retry`). Omit for the tone's own icon (info: arrows; ok: tick).
   */
  readonly icon?: IconName | null;
}

/** One row of My reports: the whole row opens the report (board 07 "Rows open the report"). */
export interface HelpReportSummary {
  /** The SUP reference exactly as the record carries it ("SUP-0213"), in `span.xr-id`. */
  readonly reference: string;
  /**
   * The report's title. PROVISIONAL (P0-31): a display-only excerpt of "What happened", made by
   * the caller; this component shows it as given.
   */
  readonly title: string;
  /** The facts after the reference: "sent 3 Oct · Shell-and-Tube Heat Exchanger · VR". */
  readonly sub: ReactNode;
  readonly href: string;
  readonly status: HelpReportStatus;
}

function ReportStatus({ status }: { readonly status: HelpReportStatus }) {
  return (
    <StatusPill tone={status.tone} icon={status.icon}>
      {status.label}
    </StatusPill>
  );
}

/* ---------------------------------------------------------------------------------------------
 * My reports — board 07 "State 2 · My reports …" and "State 2a · My reports · empty · Vendor";
 * board 05 (the Help page inside the shell).
 * ------------------------------------------------------------------------------------------- */

export interface HelpSupportHomeProps {
  /** Where "Report a problem" goes (the report form of this workspace). */
  readonly reportHref: string;
  /** The person's own reports, newest first, as the caller lists them. Empty: the empty state. */
  readonly reports: readonly HelpReportSummary[];
  /** `span.xr-meta` beside "My reports" while there are reports: "3 reports", "1 report". */
  readonly countText?: ReactNode;
  /**
   * The intro line. Defaults to board 07's words; board 05 draws "… follow what happens to your
   * report." (a board variance, reported).
   */
  readonly lead?: ReactNode;
  /** The id of the "My reports" H2 (board 07 `<frame>-mr`, board 05 `sh-rep`); generated by default. */
  readonly headingId?: string;
}

/**
 * The Help landing: the person's own reports (board 07 "The Help landing is the person’s own
 * reports. Rows open the report. Status in words."). The page header carries "Report a problem";
 * with nothing to list the action moves into the empty state (board 07 "Rules").
 */
export function HelpSupportHome({
  reportHref,
  reports,
  countText,
  lead = HOME_LEAD,
  headingId,
}: HelpSupportHomeProps) {
  const hasReports = reports.length > 0;
  const report = (
    <Link className="xr-btn xr-btn--primary" href={reportHref}>
      {REPORT_A_PROBLEM}
    </Link>
  );
  return (
    <>
      <PageHeader title={HELP} lead={lead} actions={hasReports ? report : undefined} />
      <Section title="My reports" headingId={headingId} meta={hasReports ? countText : undefined}>
        {hasReports ? (
          <Rows>
            {reports.map((item) => (
              <RowLink
                key={item.reference}
                href={item.href}
                title={item.title}
                sub={
                  <>
                    <IdChip>{item.reference}</IdChip>
                    {' · '}
                    {item.sub}
                  </>
                }
                end={<ReportStatus status={item.status} />}
              />
            ))}
          </Rows>
        ) : (
          <EmptyState
            icon="help"
            iconSize={24}
            headingLevel={3}
            title="No reports yet"
            line="small"
            actions={report}
            className="xr-x-help-empty"
          >
            If something isn’t working, report it and follow it here.
          </EmptyState>
        )}
      </Section>
    </>
  );
}

/* ---------------------------------------------------------------------------------------------
 * Report a problem — board 07 "State 1 · Report a problem · Student", "State 1a · Validation",
 * "State 1b · Sending"; board 11 "375 · AR-8 form".
 * ------------------------------------------------------------------------------------------- */

export interface HelpReportFormProps {
  /** The Help & support page: the back link above the title and Cancel go there. */
  readonly helpHref: string;
  /** "What happened?" (the textarea), controlled by the caller. */
  readonly what: string;
  readonly onWhatChange: (value: string) => void;
  /**
   * "Where did it happen?", pre-filled by the caller from the page the person came from (board 07:
   * "Filled in from the page you came from. Change it if needed."), controlled by the caller.
   */
  readonly where: string;
  readonly onWhereChange: (value: string) => void;
  /** The optional screenshot's chosen files (the caller decides what to keep; nothing uploads here). */
  readonly onScreenshotChange?: (files: FileList | null) => void;
  /**
   * The caller found "What happened?" empty on Send: board 07 "State 1a · Validation" — the
   * summary "One thing needs fixing" (linked to the field, focused) and the field's message.
   */
  readonly whatMissing?: boolean;
  /** Sending: the primary reads "Sending…", is busy and ignores presses (board 07 "State 1b"). */
  readonly sending?: boolean;
  /** "Send report" pressed (not while sending). The caller validates and sends. */
  readonly onSend: () => void;
  /** The field ids are `<idPrefix>-what`, `-where`, `-shot` (board 07 `s1-what` …); generated by default. */
  readonly idPrefix?: string;
}

/**
 * The report form (AR-8): what happened, where (pre-filled), an optional screenshot, then Cancel
 * and "Send report". Board 07 "Rules": "Fields: what happened, where (pre-filled from the page you
 * came from), optional screenshot. Nothing else." The form card is `div.xr-section` and the
 * actions are one group at the end, Cancel right before "Send report", as boards 07 and 11 draw
 * them: `div.xw-actions.xw-actions--end` (flex, wrap, 12 px gap, flex-end). The drawn inline glue
 * — the card's 24 px padding (20 px below 600 px of app width, board 11) with its 20 px column
 * gap, the group's wrap-reverse and 4 px top padding, and the primary filling the row below
 * 600 px (board 11) — is PF-14 on `div.xr-section.xr-x-help-form` (WP-0.13).
 */
export function HelpReportForm({
  helpHref,
  what,
  onWhatChange,
  where,
  onWhereChange,
  onScreenshotChange,
  whatMissing = false,
  sending = false,
  onSend,
  idPrefix,
}: HelpReportFormProps) {
  const generated = useId();
  const prefix = idPrefix ?? generated;
  const whatId = `${prefix}-what`;
  const summary = useRef<HTMLDivElement>(null);
  const [attempts, setAttempts] = useState(0);

  // Every failed Send focuses the summary again, also while it is still shown (Appendix E §5.1).
  useEffect(() => {
    if (attempts > 0 && whatMissing) summary.current?.focus();
  }, [attempts, whatMissing]);

  const send = () => {
    setAttempts((count) => count + 1);
    onSend();
  };

  return (
    <>
      <PageHeader
        back={
          <BackLink className="xr-x-help-back" href={helpHref}>
            {HELP}
          </BackLink>
        }
        title={REPORT_A_PROBLEM}
        lead="Describe what went wrong. You can follow your report in My reports."
      />
      <Stack>
        {whatMissing ? (
          <ErrorSummary
            ref={summary}
            title="One thing needs fixing"
            items={[{ fieldId: whatId, summaryText: 'Say what happened' }]}
          />
        ) : null}
        <Section className="xr-x-help-form">
          <Field
            id={whatId}
            label="What happened?"
            hint="Say what you were doing and what you saw."
            error={whatMissing ? 'Say what happened, so it can be looked into' : undefined}
          >
            <Textarea value={what} onChange={(event) => onWhatChange(event.target.value)} />
          </Field>
          <Field
            id={`${prefix}-where`}
            label="Where did it happen?"
            hint="Filled in from the page you came from. Change it if needed."
          >
            <TextInput value={where} onChange={(event) => onWhereChange(event.target.value)} />
          </Field>
          <Field
            id={`${prefix}-shot`}
            label="Screenshot"
            marker="(optional)"
            hint="A picture of the screen can help."
          >
            <FileInput
              accept="image/*"
              onChange={(event) => onScreenshotChange?.(event.currentTarget.files)}
            />
          </Field>
          <div className="xw-actions xw-actions--end">
            <Link className="xr-btn xr-btn--text" href={helpHref}>
              Cancel
            </Link>
            <Button variant="primary" busy={sending} busyLabel="Sending…" onClick={send}>
              Send report
            </Button>
          </div>
        </Section>
      </Stack>
    </>
  );
}

/* ---------------------------------------------------------------------------------------------
 * Sent — board 07 "State 1c · Sent · reference".
 * ------------------------------------------------------------------------------------------- */

export interface HelpReportSentProps {
  /** The new report's reference ("SUP-0213"). */
  readonly reference: string;
  /** Where "View my reports" goes (the Help landing). */
  readonly reportsHref: string;
  /** Where "Back to Home" goes (the workspace's home). */
  readonly homeHref: string;
  /**
   * The confirmation replaces the form in place, so focus moves to it when it appears (default;
   * Appendix E §8 "focus moves to the result"). Pass `false` when the caller moves focus itself.
   */
  readonly focusOnMount?: boolean;
  /** An id for the confirmation (it is a focus target, `tabIndex={-1}`). */
  readonly id?: string;
}

/**
 * The confirmation in place (AR-10): "Report sent", the reference and where to follow it — no
 * promise of when or by whom (board 07 "State 1c · Sent · reference"; ND-14).
 */
export function HelpReportSent({
  reference,
  reportsHref,
  homeHref,
  focusOnMount = true,
  id,
}: HelpReportSentProps) {
  const message = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (focusOnMount) message.current?.focus();
  }, [focusOnMount]);
  return (
    <MessagePage
      ref={message}
      id={id}
      tabIndex={-1}
      icon="done"
      tone="ok"
      title="Report sent"
      action={{ href: reportsHref, label: 'View my reports' }}
      secondary={{ href: homeHref, label: 'Back to Home' }}
    >
      Your reference is <IdChip>{reference}</IdChip>. You can follow it in My reports.
    </MessagePage>
  );
}

/* ---------------------------------------------------------------------------------------------
 * Report detail — board 07 "State 3 · Report detail · resolved with note · Faculty" and
 * "State 3a · Report detail · reopened · Content Manager".
 * ------------------------------------------------------------------------------------------- */

export interface HelpReportDetailProps {
  /** The Help & support page (the back link). */
  readonly helpHref: string;
  /** Where "Report a problem" at the foot goes. */
  readonly reportHref: string;
  /** The SUP reference ("SUP-0198"), drawn above the title. */
  readonly reference: string;
  /** The report's title (PROVISIONAL P0-31: a display-only excerpt made by the caller). */
  readonly title: string;
  readonly status: HelpReportStatus;
  /** The date it was sent, as the caller formats it ("21 Sep"): "Sent 21 Sep". */
  readonly sent: string;
  /**
   * The resolution note, first on the page when the report is resolved (board 07 "The resolution
   * note is the first thing on the page"): "Resolution note · 23 Sep" + the note.
   */
  readonly resolution?: { readonly date: string; readonly note: ReactNode };
  /** Reopened: "This report is open again" — "It was reopened on 6 Oct. You can follow it here." */
  readonly reopened?: { readonly date: string };
  /**
   * The body of "What you reported" (what happened · where · screenshot). Board 07 draws it as a
   * canvas `dl.doc-kv`, which is not a product class; KeyValueList is Phase 1, so the caller
   * supplies this content.
   */
  readonly reported: ReactNode;
  /** The body of "History": a Timeline, newest first ("History comes last"). */
  readonly history: ReactNode;
  /** The section heading ids are `<idPrefix>-wr` and `<idPrefix>-hi` (board 07); generated by default. */
  readonly idPrefix?: string;
}

/**
 * A report's detail (AR-3): reference, title, status in words and when it was sent; the
 * resolution note or the reopened notice first; what was reported; the history last; and a way to
 * report something else. The reporter has no reopen control (board 07 "Rules": resolving and
 * reopening are Super Admin actions).
 */
export function HelpReportDetail({
  helpHref,
  reportHref,
  reference,
  title,
  status,
  sent,
  resolution,
  reopened,
  reported,
  history,
  idPrefix,
}: HelpReportDetailProps) {
  const generated = useId();
  const prefix = idPrefix ?? generated;
  return (
    <>
      <PageHeader
        back={
          <BackLink className="xr-x-help-back" href={helpHref}>
            {HELP}
          </BackLink>
        }
        recordId={reference}
        title={title}
        meta={
          <>
            <ReportStatus status={status} />
            <span>Sent {sent}</span>
          </>
        }
      />
      <Stack>
        {resolution ? (
          <Notice tone="ok" icon="reviewedByMe" title={`Resolution note · ${resolution.date}`}>
            {resolution.note}
          </Notice>
        ) : null}
        {reopened ? (
          <Notice icon="retry" title="This report is open again">
            It was reopened on {reopened.date}. You can follow it here.
          </Notice>
        ) : null}
        <Section title="What you reported" headingId={`${prefix}-wr`}>
          <SectionBody>{reported}</SectionBody>
        </Section>
        <Section title="History" headingId={`${prefix}-hi`}>
          <SectionBody>{history}</SectionBody>
        </Section>
        <p className="xr-small xr-x-help-foot">
          Something else isn’t working? <Link href={reportHref}>{REPORT_A_PROBLEM}</Link>
        </p>
      </Stack>
    </>
  );
}
