// Generates src/tokens/v46-constants.ts — the only TypeScript constants of the v46 visual system
// (Appendix E §1.2 T-2; Appendix F WP-0.5): the approved container-query thresholds and the two
// focus colours. Everything else stays a CSS custom property in the verbatim xr-foundation.css;
// there is no second token system and no hand-written TS palette.
//
// Inputs (read only): design/handoff-v46/canvas-v46/project/handoff/tokens.json and the
// byte-identical stylesheet copies in src/styles/v46/. Run `pnpm --filter @xr/ui generate:constants`
// only after an owner-approved change to the frozen handoff; the drift test
// (src/tokens/v46-constants.test.ts) fails whenever the committed file and its sources disagree.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

const packageRoot = join(import.meta.dirname, '..');
const repositoryRoot = join(packageRoot, '..', '..', '..');

export const TOKENS_JSON = join(
  repositoryRoot,
  'design',
  'handoff-v46',
  'canvas-v46',
  'project',
  'handoff',
  'tokens.json',
);
export const SHEETS_DIRECTORY = join(packageRoot, 'src', 'styles', 'v46');
export const OUTPUT = join(packageRoot, 'src', 'tokens', 'v46-constants.ts');

/** The eight v46 stylesheets in the B8-07 load order. */
export const SHEETS = [
  'xr-foundation.css',
  'xr-public.css',
  'xr-workspace.css',
  'xr-learning.css',
  'xr-assess.css',
  'xr-vendor.css',
  'xr-govern.css',
  'xr-admin.css',
];

/**
 * The approved thresholds (owner WP-0.5 authorisation: 600, 760, 860, 1024, 1280) with what each
 * switches, from Appendix E §6.1. The containers that use each one are read from the sheets.
 */
export const APPROVED_THRESHOLDS = [
  {
    name: 'phone',
    px: 600,
    meaning: 'Below: phone scale, full-width actions and dialog buttons, toolbar wraps.',
  },
  {
    name: 'labelledRows',
    px: 760,
    meaning: 'Below (content): tables become labelled rows and comparisons stack.',
  },
  {
    name: 'decisionPanel',
    px: 860,
    meaning: 'From (content): decision layout with its side panel; flow summary panel.',
  },
  {
    name: 'sidebar',
    px: 1024,
    meaning: 'From (app): sidebar and white top bar; below: Menu and drawer (public: Menu sheet).',
  },
  {
    name: 'fullSidebar',
    px: 1280,
    meaning: 'From (app): full 248 px sidebar; public: Selection label, 4-up grids.',
  },
];

/** Every named container whose queries use `px`, as `max-width:<px − 0.02>px` or `min-width:<px>px`. */
export function containersUsing(css, px) {
  const below = `${(px - 0.02).toFixed(2)}px`;
  const containers = new Set();
  for (const match of css.matchAll(/@container\s+([a-z][\w-]*)\s+([^{]+)\{/g)) {
    const [, name, condition] = match;
    const widths = [...condition.matchAll(/\((min|max)-width:\s*([\d.]+px)\)/g)];
    if (
      widths.some(
        ([, kind, value]) =>
          (kind === 'min' && value === `${px}px`) || (kind === 'max' && value === below),
      )
    ) {
      containers.add(name);
    }
  }
  return [...containers].sort();
}

const quote = (value) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

/** The generated module source, formatted as Prettier formats it (the format check runs on it). */
export function renderV46Constants({ tokensJson, css }) {
  const tokens = JSON.parse(tokensJson).tokens.color;
  const focus = tokens['--xr-focus'];
  const focusDark = tokens['--xr-focus-dark'];
  if (!focus || !focusDark) throw new Error('tokens.json has no --xr-focus / --xr-focus-dark');

  const thresholds = APPROVED_THRESHOLDS.map((threshold) => {
    const containers = containersUsing(css, threshold.px);
    if (containers.length === 0) {
      throw new Error(`No v46 container query uses the approved threshold ${threshold.px}px`);
    }
    return { ...threshold, containers };
  });

  const lines = [
    '/**',
    ' * GENERATED by scripts/generate-v46-constants.mjs — do not edit by hand.',
    ' *',
    ' * Sources (read only): design/handoff-v46/canvas-v46/project/handoff/tokens.json and the',
    ' * byte-identical v46 stylesheet copies in src/styles/v46/. Drift test:',
    ' * src/tokens/v46-constants.test.ts. Every other v46 value stays a CSS custom property in',
    ' * xr-foundation.css (Appendix E §1.2 T-1, T-2): there is no TypeScript palette.',
    ' */',
    '',
    '/**',
    ' * The approved v46 container-query thresholds in CSS px (Appendix E §6.1). Below a threshold',
    ' * the sheets apply `max-width: <px − 0.02>px`; from it, `min-width: <px>px`. `containers` lists',
    ' * the named containers (`xr-app`, `xr-content`, `xp`) whose queries use the threshold.',
    ' */',
    'export const V46_CONTAINER_THRESHOLDS = {',
  ];
  for (const threshold of thresholds) {
    lines.push(
      `  /** ${threshold.meaning} */`,
      `  ${threshold.name}: { px: ${threshold.px}, containers: [${threshold.containers.map(quote).join(', ')}] },`,
    );
  }
  lines.push(
    '} as const;',
    '',
    '/**',
    ' * Focus-ring colours: `--xr-focus` on light surfaces and `--xr-focus-dark` on navy (board 02',
    ' * "Focus on navy · Ring #F7C95B"; PF-07). For contrast and computed-style tests.',
    ' */',
    'export const V46_FOCUS_COLOURS = {',
    `  focus: ${quote(focus)},`,
    `  focusDark: ${quote(focusDark)},`,
    '} as const;',
    '',
  );
  return lines.join('\n');
}

/** Reads the real inputs. */
export function readInputs() {
  return {
    tokensJson: readFileSync(TOKENS_JSON, 'utf8'),
    css: SHEETS.map((sheet) => readFileSync(join(SHEETS_DIRECTORY, sheet), 'utf8')).join('\n'),
  };
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  writeFileSync(OUTPUT, renderV46Constants(readInputs()));
  process.stdout.write(`wrote ${OUTPUT}\n`);
}
